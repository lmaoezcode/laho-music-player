#!/usr/bin/env python3
"""Generate the LaHo Music Player icon set from one geometry definition.

Original artwork for LaHo (not derived from Rhythm's logo): a white "L" whose
foot is the baseline of an amber three-bar waveform, on a teal-to-navy tile.

Outputs (paths relative to the repo root):
  app/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml
  app/src/main/res/drawable/ic_notification.xml          (24dp white silhouette)
  app/src/main/res/drawable/rhythm_logo.xml               (round badge: splash + in-app logo)
  app/src/main/res/drawable/rhythm_splash_logo.xml        (same badge)
  app/src/main/res/drawable/rhythm_icon_small.xml         (single-colour mark)
  app/src/main/res/mipmap-*/ic_launcher{,_round}.webp     (legacy raster fallbacks)
  assets/branding/laho_icon.svg, assets/icon.png, docs/branding/laho_icon_preview.png

Drawable *names* stay as upstream (rhythm_logo, ...) so Kotlin code and future
upstream merges keep working; only the artwork changes.

Requires: pip install resvg-py pillow
Run from the repo root:  python scripts/branding/gen_laho_icon.py
"""
from __future__ import annotations

import io
import os
from pathlib import Path

import resvg_py
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res"

# ---- Brand colours --------------------------------------------------------
TEAL = "#12A4A0"      # gradient start (top-left)
NAVY = "#1B3B6F"      # gradient end (bottom-right)
WHITE = "#FFFFFF"
AMBER = "#FFC857"     # waveform accent

# ---- Geometry (108 x 108 adaptive-icon viewport, safe zone r=33 @ 54,54) ----
def rrect(x: float, y: float, w: float, h: float, r: float) -> str:
    """Rounded-rectangle path data usable in both SVG and Android vectors."""
    r = min(r, w / 2, h / 2)
    return (
        f"M{x + r:g},{y:g}H{x + w - r:g}A{r:g},{r:g} 0 0 1 {x + w:g},{y + r:g}"
        f"V{y + h - r:g}A{r:g},{r:g} 0 0 1 {x + w - r:g},{y + h:g}"
        f"H{x + r:g}A{r:g},{r:g} 0 0 1 {x:g},{y + h - r:g}"
        f"V{y + r:g}A{r:g},{r:g} 0 0 1 {x + r:g},{y:g}Z"
    )

STROKE = 11.0
# The "L": stem + foot drawn as two overlapping rounded bars (same winding).
L_PATH = rrect(33, 29, STROKE, 49, STROKE / 2) + rrect(33, 67, 44, STROKE, STROKE / 2)
# Waveform: three rounded bars centred on y=47, sitting in the L's corner.
BAR_W = 7.0
BARS = [(50, 16), (60, 30), (70, 20)]  # (x, height)
WAVE_PATH = "".join(rrect(x, 47 - h / 2, BAR_W, h, BAR_W / 2) for x, h in BARS)
LAUNCHER_SCALE = 0.9  # keeps the mark (44x49) comfortably inside the 66dp safe zone
BADGE_SCALE = 0.8     # mark inside the round badge (splash / in-app logo)


# ---- Android vector writers ----------------------------------------------
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
NOTE = "<!-- Generated by scripts/branding/gen_laho_icon.py - LaHo Music Player icon (original artwork). -->\n"


def vector(body: str, size_dp: int = 108, viewport: int = 108, aapt: bool = False) -> str:
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    return (
        HEADER + NOTE +
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
        f'    android:width="{size_dp}dp"\n    android:height="{size_dp}dp"\n'
        f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
        f"{body}</vector>\n"
    )


def a_path(d: str, color: str, indent: str = "    ") -> str:
    return f'{indent}<path\n{indent}    android:fillColor="{color}"\n{indent}    android:pathData="{d}" />\n'


def a_gradient_path(d: str, x0, y0, x1, y1, indent: str = "    ") -> str:
    return (
        f"{indent}<path android:pathData=\"{d}\">\n"
        f'{indent}    <aapt:attr name="android:fillColor">\n'
        f'{indent}        <gradient\n'
        f'{indent}            android:type="linear"\n'
        f'{indent}            android:startX="{x0}" android:startY="{y0}"\n'
        f'{indent}            android:endX="{x1}" android:endY="{y1}"\n'
        f'{indent}            android:startColor="{TEAL}"\n'
        f'{indent}            android:endColor="{NAVY}" />\n'
        f"{indent}    </aapt:attr>\n"
        f"{indent}</path>\n"
    )


def a_group(inner: str, scale: float = 1.0, pivot: float = 54, tx: float = 0, ty: float = 0) -> str:
    return (
        f'    <group android:pivotX="{pivot:g}" android:pivotY="{pivot:g}"'
        f' android:scaleX="{scale:g}" android:scaleY="{scale:g}"'
        f' android:translateX="{tx:g}" android:translateY="{ty:g}">\n'
        + "".join("    " + line + "\n" for line in inner.splitlines())
        + "    </group>\n"
    )


def mark(l_color: str, wave_color: str) -> str:
    return a_path(L_PATH, l_color) + a_path(WAVE_PATH, wave_color)


CIRCLE = "M54,20A34,34 0 1 1 54,88A34,34 0 1 1 54,20Z"  # r=34 badge (splash mask is r=36)
FULL = "M0,0H108V108H0Z"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(ROOT))


def write_android() -> None:
    d = RES / "drawable"
    write(d / "ic_launcher_background.xml", vector(a_gradient_path(FULL, 0, 0, 108, 108), aapt=True))
    write(d / "ic_launcher_foreground.xml", vector(a_group(mark(WHITE, AMBER), scale=LAUNCHER_SCALE)))
    write(d / "ic_launcher_monochrome.xml", vector(a_group(mark("#000000", "#000000"), scale=LAUNCHER_SCALE)))
    # Badge = gradient disc + mark scaled to sit inside it.
    badge = a_gradient_path(CIRCLE, 20, 20, 88, 88) + a_group(mark(WHITE, AMBER), scale=BADGE_SCALE)
    write(d / "rhythm_logo.xml", vector(badge, aapt=True))
    write(d / "rhythm_splash_logo.xml", vector(badge, aapt=True))
    write(d / "rhythm_icon_small.xml", vector(a_group(mark(TEAL, TEAL), scale=1.35)))
    # Status-bar icon: 24dp, white, mark scaled up to fill the canvas (~22/24 dp).
    write(d / "ic_notification.xml", vector(a_group(mark(WHITE, WHITE), scale=1.75), size_dp=24))


# ---- SVG + raster ---------------------------------------------------------
def svg(body: str, size: int = 108) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">'
        f'<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{TEAL}"/><stop offset="1" stop-color="{NAVY}"/></linearGradient></defs>'
        f"{body}</svg>"
    )


def s_mark(l_color: str, wave_color: str, transform: str = "") -> str:
    t = f' transform="{transform}"' if transform else ""
    return f'<g{t}><path d="{L_PATH}" fill="{l_color}"/><path d="{WAVE_PATH}" fill="{wave_color}"/></g>'


def scaled(s: float) -> str:
    return f"translate(54 54) scale({s}) translate(-54 -54)"


def render(svg_text: str, px: int) -> Image.Image:
    data = resvg_py.svg_to_bytes(svg_string=svg_text, width=px, height=px)
    return Image.open(io.BytesIO(bytes(data))).convert("RGBA")


def full_icon_svg() -> str:
    return svg(f'<rect width="108" height="108" fill="url(#g)"/>' + s_mark(WHITE, AMBER, scaled(LAUNCHER_SCALE)))


def masked(img: Image.Image, shape: str) -> Image.Image:
    """Apply a launcher mask to a full-bleed 108-unit render (crop 72/108 visible area like Android)."""
    n = img.width
    inset = round(n * 18 / 108)
    crop = img.crop((inset, inset, n - inset, n - inset)).resize((n, n), Image.LANCZOS)
    mask = Image.new("L", (n * 4, n * 4), 0)
    dr = ImageDraw.Draw(mask)
    if shape == "circle":
        dr.ellipse((0, 0, n * 4 - 1, n * 4 - 1), fill=255)
    else:  # rounded square / squircle-ish
        dr.rounded_rectangle((0, 0, n * 4 - 1, n * 4 - 1), radius=int(n * 4 * 0.23), fill=255)
    mask = mask.resize((n, n), Image.LANCZOS)
    out = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    out.paste(crop, (0, 0), mask)
    return out


def write_rasters() -> None:
    sizes = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    big = render(full_icon_svg(), 1296)
    sq = masked(big, "square")
    rd = masked(big, "circle")
    for q, px in sizes.items():
        folder = RES / f"mipmap-{q}"
        sq.resize((px, px), Image.LANCZOS).save(folder / "ic_launcher.webp", "WEBP", lossless=True)
        rd.resize((px, px), Image.LANCZOS).save(folder / "ic_launcher_round.webp", "WEBP", lossless=True)
        print("wrote", (folder / "ic_launcher{,_round}.webp").relative_to(ROOT))

    (ROOT / "assets/branding").mkdir(parents=True, exist_ok=True)
    write(ROOT / "assets/branding/laho_icon.svg", full_icon_svg())
    write(ROOT / "assets/branding/laho_badge.svg",
          svg(f'<circle cx="54" cy="54" r="34" fill="url(#g)"/>' + s_mark(WHITE, AMBER, scaled(BADGE_SCALE))))
    sq.resize((512, 512), Image.LANCZOS).save(ROOT / "assets/icon.png")
    print("wrote assets/icon.png")


def write_preview(out: Path) -> None:
    """Contact sheet: launcher shapes, themed icon, small sizes, splash, status bar."""
    W, H = 1200, 760
    sheet = Image.new("RGBA", (W, H), "#F4F6F8")
    dr = ImageDraw.Draw(sheet)
    big = render(full_icon_svg(), 1296)
    tiles = [("Adaptive - circle", masked(big, "circle")), ("Adaptive - squircle", masked(big, "square"))]
    # Themed (monochrome) icon, Material You style tint.
    mono = render(svg('<rect width="108" height="108" fill="#D7E8E6"/>' + s_mark("#0B4F4C", "#0B4F4C", scaled(LAUNCHER_SCALE))), 1296)
    tiles.append(("Themed icon (monochrome)", masked(mono, "circle")))
    monod = render(svg('<rect width="108" height="108" fill="#16302E"/>' + s_mark("#9CE3DD", "#9CE3DD", scaled(LAUNCHER_SCALE))), 1296)
    tiles.append(("Themed icon (dark)", masked(monod, "circle")))
    x = 40
    for label, img in tiles:
        sheet.alpha_composite(img.resize((240, 240), Image.LANCZOS), (x, 40))
        dr.text((x, 292), label, fill="#33414E")
        x += 285
    # Small sizes on a wallpaper-like strip.
    dr.rounded_rectangle((40, 340, 600, 500), radius=18, fill="#2C3E50")
    x = 70
    for px in (96, 72, 48, 36, 24):
        sheet.alpha_composite(masked(big, "circle").resize((px, px), Image.LANCZOS), (x, 420 - px // 2))
        dr.text((x, 470), f"{px}px", fill="#DDE6EE")
        x += px + 40
    dr.text((40, 510), "Launcher sizes (48dp = 144px on xxhdpi)", fill="#33414E")
    # Splash (light + dark).
    badge = svg(f'<circle cx="54" cy="54" r="34" fill="url(#g)"/>' + s_mark(WHITE, AMBER, scaled(BADGE_SCALE)))
    for i, bg in enumerate(("#FFFFFF", "#1C1B1F")):
        x0 = 640 + i * 270
        dr.rounded_rectangle((x0, 340, x0 + 240, 700), radius=24, fill=bg, outline="#C9D2DA")
        sheet.alpha_composite(render(badge, 160), (x0 + 40, 440))
    dr.text((640, 712), "Splash screen (light / dark)", fill="#33414E")
    # Status bar notification icon.
    dr.rounded_rectangle((40, 560, 600, 620), radius=12, fill="#111418")
    note = render(svg(s_mark(WHITE, WHITE, scaled(1.75))), 40)
    sheet.alpha_composite(note, (60, 570))
    dr.text((110, 582), "12:30   status-bar / notification small icon (24dp)", fill="#E8EEF3")
    dr.text((40, 640), "LaHo Music Player - original icon: 'L' + waveform", fill="#33414E")
    dr.text((40, 662), f"Colours: teal {TEAL} -> navy {NAVY}, mark white, waveform amber {AMBER}", fill="#33414E")
    out.parent.mkdir(parents=True, exist_ok=True)
    sheet.convert("RGB").save(out)
    print("wrote", out)


if __name__ == "__main__":
    write_android()
    write_rasters()
    write_preview(ROOT / "docs/branding/laho_icon_preview.png")
    extra = os.environ.get("LAHO_PREVIEW_OUT")
    if extra:
        write_preview(Path(extra))
